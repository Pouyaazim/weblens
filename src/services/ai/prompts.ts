export function buildMessages(task: AiTask, payload: Record<string, string>, language: 'fa' | 'en') {
  const payloadText = Object.entries(payload)
    .map(([k, v]) => `## ${k}\n${v}`)
    .join('\n\n');
  const langNote = language === 'fa' ? 'پاسخ را به زبان فارسی بنویس.' : 'Respond in English.';
  return [
    { role: 'system' as const, content: `${SYSTEM_BASE}\n${langNote}` },
    { role: 'user' as const, content: `${TASK_PROMPTS[task]}\n\n${payloadText}` },
  ];
}
